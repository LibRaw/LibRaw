struct stage1_data
{
    uint8_t h_gcli0[0x34];  // 52
    uint8_t *gcli;
    precinct_data_t *precincts;  // 2592=40*MAX_PACKETS(64)
    bool seg_empty[52];
    int *worker_buffs;
    idwt_state_t idwt_state[XS_MAX_IMAGE_COMPONENTS];
    int *idwt_b1_v2;
    int *idwt_b2_v2;

    stage1_data(uint32_t line_stride)
    {
        uint32_t line_stride_4k = ((line_stride >> 7) + 31) >> 5 << 12;
        buf.resize(line_stride_4k + sizeof(int32_t)*7*line_stride_4k);
        gcli = buf.data();
        worker_buffs = (int32_t *)(gcli + line_stride_4k);
        idwt_b1_v2 = worker_buffs + 5*line_stride_4k;
        idwt_b2_v2 = idwt_b1_v2 + line_stride_4k;
        precs.resize(0xA20); // 2592=40*MAX_PACKETS(64)
        precincts = precs.data();
    }
private:
    std::vector<uint8_t> buf;
    std::vector<precinct_data_t> precs;
};

